package com.jarforge.ide.data.storage.templates

import com.jarforge.ide.data.model.Loader
import com.jarforge.ide.data.model.Project

/** Unverified: not checked against a real Forge build. Mixin is not offered for Forge. */
internal object ForgeTemplate : LoaderTemplate {
    override val loader: Loader = Loader.FORGE
    override val supportsMixin: Boolean = false

    override fun generate(project: Project): List<GeneratedFile> {
        val className = TemplateSupport.mainClassName(project)
        return listOf(
            GeneratedFile(
                TemplateSupport.javaSourcePath(project, "$className.java"),
                mainSource(project, className)
            ),
            GeneratedFile("src/main/resources/META-INF/mods.toml", modsToml(project)),
            TemplateSupport.readme(project)
        )
    }

    private fun mainSource(project: Project, className: String): String = """
        package ${project.packageName};

        import net.minecraftforge.fml.common.Mod;

        @Mod($className.MOD_ID)
        public class $className {
            public static final String MOD_ID = "${project.modId}";

            public $className() {
            }
        }
    """.trimIndent() + "\n"

    private fun modsToml(project: Project): String = """
        modLoader="javafml"
        loaderVersion="[1,)"
        license="All Rights Reserved"

        [[mods]]
        modId="${project.modId}"
        version="${project.modVersion}"
        displayName=${TemplateSupport.tomlString(project.name)}
        description='''Generated by Jarforge IDE.'''

        [[dependencies.${project.modId}]]
        modId="forge"
        mandatory=true
        versionRange="[1,)"
        ordering="NONE"
        side="BOTH"

        [[dependencies.${project.modId}]]
        modId="minecraft"
        mandatory=true
        versionRange="[${project.minecraftVersion},)"
        ordering="NONE"
        side="BOTH"
    """.trimIndent() + "\n"
}
