package com.jarforge.ide.data.storage.templates

import com.jarforge.ide.data.model.Loader
import com.jarforge.ide.data.model.MinecraftVersions
import com.jarforge.ide.data.model.Project
import com.jarforge.ide.domain.ProjectNaming
import org.json.JSONArray
import org.json.JSONObject

data class GeneratedFile(
    val relativePath: String,
    val content: String
)

interface LoaderTemplate {
    val loader: Loader

    /** Whether the Mixin-ready template is offered for this loader. */
    val supportsMixin: Boolean

    /** True only once generated projects are confirmed to build. Nothing is verified yet. */
    val buildVerified: Boolean get() = false

    fun generate(project: Project): List<GeneratedFile>
}

object LoaderTemplates {
    fun forLoader(loader: Loader): LoaderTemplate = when (loader) {
        Loader.FABRIC -> FabricTemplate
        Loader.FORGE -> ForgeTemplate
        Loader.NEOFORGE -> NeoForgeTemplate
    }
}

/** Helpers shared by the loader templates. */
internal object TemplateSupport {

    fun mainClassName(project: Project): String = ProjectNaming.className(project.modId)

    fun javaSourcePath(project: Project, fileName: String): String =
        "src/main/java/${project.packageName.replace('.', '/')}/$fileName"

    fun javaVersion(project: Project): Int =
        MinecraftVersions.find(project.loader, project.minecraftVersion)?.javaVersion ?: 21

    /** Quoted TOML basic string. */
    fun tomlString(value: String): String {
        val sb = StringBuilder("\"")
        for (c in value) {
            when (c) {
                '\\' -> sb.append("\\\\")
                '"' -> sb.append("\\\"")
                else -> sb.append(c)
            }
        }
        return sb.append('"').toString()
    }

    fun mixinFiles(project: Project): List<GeneratedFile> {
        val config = JSONObject()
            .put("required", true)
            .put("minVersion", "0.8")
            .put("package", "${project.packageName}.mixin")
            .put("mixins", JSONArray())
            .put("client", JSONArray())
            .put("server", JSONArray())
            .put("injectors", JSONObject().put("defaultRequire", 1))
        return listOf(
            GeneratedFile(
                "src/main/resources/${project.modId}.mixins.json",
                config.toString(2) + "\n"
            ),
            GeneratedFile(
                "src/main/java/${project.packageName.replace('.', '/')}/mixin/package-info.java",
                "package ${project.packageName}.mixin;\n"
            )
        )
    }

    fun readme(project: Project): GeneratedFile {
        val loader = project.loader.displayName
        val content = """
            # ${project.name}

            Generated by Jarforge IDE.

            - Loader: $loader
            - Minecraft: ${project.minecraftVersion}
            - Mod ID: ${project.modId}
            - Package: ${project.packageName}
            - Template: ${project.template.displayName}

            ## Status

            This is a source skeleton only. It has NOT been built or verified against $loader ${project.minecraftVersion}.
            Jarforge IDE does not generate Gradle build files yet, so this project cannot be compiled or run yet.
        """.trimIndent() + "\n"
        return GeneratedFile("README.md", content)
    }
}
