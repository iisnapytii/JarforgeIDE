package com.jarforge.ide.data.storage.templates

import com.jarforge.ide.data.model.Loader
import com.jarforge.ide.data.model.Project
import com.jarforge.ide.data.model.ProjectTemplate
import org.json.JSONArray
import org.json.JSONObject

/** Unverified: not checked against a real Fabric build. */
internal object FabricTemplate : LoaderTemplate {
    override val loader: Loader = Loader.FABRIC
    override val supportsMixin: Boolean = true

    override fun generate(project: Project): List<GeneratedFile> {
        val className = TemplateSupport.mainClassName(project)
        val files = mutableListOf<GeneratedFile>()
        files += GeneratedFile(
            TemplateSupport.javaSourcePath(project, "$className.java"),
            mainSource(project, className)
        )
        files += GeneratedFile(
            "src/main/resources/fabric.mod.json",
            modJson(project, className)
        )
        if (project.template == ProjectTemplate.MIXIN_READY) {
            files += TemplateSupport.mixinFiles(project)
        }
        files += TemplateSupport.readme(project)
        return files
    }

    private fun mainSource(project: Project, className: String): String = """
        package ${project.packageName};

        import net.fabricmc.api.ModInitializer;

        public class $className implements ModInitializer {
            public static final String MOD_ID = "${project.modId}";

            @Override
            public void onInitialize() {
                // Mod initialization code goes here.
            }
        }
    """.trimIndent() + "\n"

    private fun modJson(project: Project, className: String): String {
        val o = JSONObject()
        o.put("schemaVersion", 1)
        o.put("id", project.modId)
        o.put("version", project.modVersion)
        o.put("name", project.name)
        o.put("description", "Generated by Jarforge IDE.")
        o.put("license", "All Rights Reserved")
        o.put("environment", "*")
        o.put(
            "entrypoints",
            JSONObject().put("main", JSONArray().put("${project.packageName}.$className"))
        )
        if (project.template == ProjectTemplate.MIXIN_READY) {
            o.put("mixins", JSONArray().put("${project.modId}.mixins.json"))
        }
        o.put(
            "depends",
            JSONObject()
                .put("fabricloader", "*")
                .put("minecraft", ">=${project.minecraftVersion}")
                .put("java", ">=${TemplateSupport.javaVersion(project)}")
        )
        return o.toString(2) + "\n"
    }
}
