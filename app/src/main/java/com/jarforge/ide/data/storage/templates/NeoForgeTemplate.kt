package com.jarforge.ide.data.storage.templates

import com.jarforge.ide.data.model.Loader
import com.jarforge.ide.data.model.Project
import com.jarforge.ide.data.model.ProjectTemplate

/**
 * Unverified: not checked against a real NeoForge build.
 * File layout and @Mod constructor follow the NeoForge docs.
 */
internal object NeoForgeTemplate : LoaderTemplate {
    override val loader: Loader = Loader.NEOFORGE
    override val supportsMixin: Boolean = true

    override fun generate(project: Project): List<GeneratedFile> {
        val className = TemplateSupport.mainClassName(project)
        val files = mutableListOf<GeneratedFile>()
        files += GeneratedFile(
            TemplateSupport.javaSourcePath(project, "$className.java"),
            mainSource(project, className)
        )
        files += GeneratedFile(
            "src/main/resources/META-INF/neoforge.mods.toml",
            modsToml(project)
        )
        if (project.template == ProjectTemplate.MIXIN_READY) {
            files += TemplateSupport.mixinFiles(project)
        }
        files += TemplateSupport.readme(project)
        return files
    }

    private fun mainSource(project: Project, className: String): String = """
        package ${project.packageName};

        import net.neoforged.bus.api.IEventBus;
        import net.neoforged.fml.common.Mod;

        @Mod($className.MOD_ID)
        public class $className {
            public static final String MOD_ID = "${project.modId}";

            public $className(IEventBus modEventBus) {
            }
        }
    """.trimIndent() + "\n"

    private fun modsToml(project: Project): String {
        val base = """
            modLoader="javafml"
            loaderVersion="[1,)"
            license="All Rights Reserved"

            [[mods]]
            modId="${project.modId}"
            version="${project.modVersion}"
            displayName=${TemplateSupport.tomlString(project.name)}
            description='''Generated by Jarforge IDE.'''

            [[dependencies.${project.modId}]]
            modId="neoforge"
            type="required"
            versionRange="[1,)"
            ordering="NONE"
            side="BOTH"

            [[dependencies.${project.modId}]]
            modId="minecraft"
            type="required"
            versionRange="[${project.minecraftVersion},)"
            ordering="NONE"
            side="BOTH"
        """.trimIndent() + "\n"

        return if (project.template == ProjectTemplate.MIXIN_READY) {
            base + "\n[[mixins]]\nconfig=\"${project.modId}.mixins.json\"\n"
        } else {
            base
        }
    }
}
